/* ============================================================================
 *  8. 调参实战步骤
 * ============================================================================
 *
 *  ┌──────────────────────────────────────────────────────────────────────┐
 *  │                                                                      │
 *  │  第一步：固定增益，只调曝光                                            │
 *  │  ────────────────────────                                             │
 *  │  1. 增益保持默认 32 不动                                              │
 *  │  2. 从曝光 = 100 开始                                                 │
 *  │  3. 看屏幕（ips114_show_gray_image 显示原始灰度图）                    │
 *  │  4. 赛道边缘清晰吗？反光区域还亮吗？                                   │
 *  │                                                                      │
 *  │     反光太亮 → 降低曝光到 80、60、50...                                │
 *  │     赛道太暗 → 提高曝光到 120、150、200...                             │
 *  │                                                                      │
 *  │  5. 找到曝光值 X，使得：                                              │
 *  │     ✓ 赛道边缘清晰可见                                                │
 *  │     ✓ 反光区域亮度明显降低                                            │
 *  │     ✓ 赛道黑白对比度足够                                              │
 *  │                                                                      │
 *  ├──────────────────────────────────────────────────────────────────────┤
 *  │                                                                      │
 *  │  第二步：固定曝光，微调增益                                            │
 *  │  ────────────────────────                                             │
 *  │  1. 曝光固定为上一步的 X 值                                           │
 *  │  2. 尝试增益 = 16（最低）：画面会不会太暗？                            │
 *  │  3. 尝试增益 = 24：平衡点？                                           │
 *  │  4. 尝试增益 = 32（默认）：反光回来没？                                │
 *  │  5. 找到增益值 Y，使得：                                              │
 *  │     ✓ 整体亮度适中                                                    │
 *  │     ✓ 噪声不明显（黑区无零星白点）                                     │
 *  │                                                                      │
 *  ├──────────────────────────────────────────────────────────────────────┤
 *  │                                                                      │
 *  │  第三步：验证二值化效果                                                │
 *  │  ────────────────────────                                             │
 *  │  1. 看 bin_image 的显示效果（ips114_show_gray_image 最后参数为1）       │
 *  │  2. 赛道 = 纯白，背景 = 纯黑，边界清晰？                              │
 *  │  3. 直角弯前方（无赛道区域）应该是黑色的？                             │
 *  │  4. 如果还有白色误判 → 曝光再降一点                                    │
 *  │                                                                      │
 *  └──────────────────────────────────────────────────────────────────────┘
 *
 *
 *  快速参考表（根据场地亮度选择）：
 *
 *  ┌──────────────┬────────────┬────────┬──────────────────────────────┐
 *  │ 场地亮度      │ 曝光时间    │ 增益   │ 备注                          │
 *  ├──────────────┼────────────┼────────┼──────────────────────────────┤
 *  │ 强光/户外     │ 40 ~ 80    │ 16 ~ 24│ 最容易反光，需要压低参数       │
 *  │ 室内日光灯    │ 80 ~ 150   │ 24 ~ 32│ 最常见的比赛环境               │
 *  │ 偏暗/地下室   │ 150 ~ 300  │ 32 ~ 48│ 需要较高亮度才能看清赛道       │
 *  │ 很暗          │ 300 ~ 512  │ 48 ~ 64│ 极端情况，噪声会比较大         │
 *  └──────────────┴────────────┴────────┴──────────────────────────────┘
 */


/* ============================================================================
 *  9. 常见问题与解决
 * ============================================================================
 *
 *  Q1: 降低曝光后赛道边缘变得模糊/锯齿明显？
 *  ──────────────────────────────────────────────────────────────
 *  A:  曝光太低导致边缘过渡区变窄，二值化后的边界不够平滑。
 *      解决：适当提高曝光（比如从 80 调到 100），
 *      或者在 image_binarize() 中调整 THRESH_MIN/THRESH_MAX 范围。
 *
 *
 *  Q2: 降低曝光后暗区完全看不到（全黑）？
 *  ──────────────────────────────────────────────────────────────
 *  A:  曝光太低，暗区的灰度值全部低于二值化阈值。
 *      解决：提高曝光，或者降低 THRESH_MIN（比如从 80 改到 60）。
 *
 *
 *  Q3: 画面有明显闪烁/亮度不稳？
 *  ──────────────────────────────────────────────────────────────
 *  A:  可能是自动曝光没关（AUTO_EXP != 0）。
 *      检查：mt9v03x_set_confing_buffer_1[MT9V03X_DOUBLE_AUTO_EXP][1] 是否为 0。
 *
 *
 *  Q4: 调了曝光但画面完全没变化？
 *  ──────────────────────────────────────────────────────────────
 *  A:  可能原因：
 *      ① mt9v03x_set_exposure_time_sccb() 调用顺序错误（必须在 init 之后）
 *      ② 配置没有正确发送到摄像头
 *      ③ 修改了宏定义但没有重新编译下载
 *
 *
 *  Q5: 增益调到 16 后画面太暗，调高曝光又反光，怎么办？
 *  ──────────────────────────────────────────────────────────────
 *  A:  这是曝光和增益的矛盾。解决方案：
 *      ① 物理方法：给摄像头加偏振片/滤光片，过滤特定角度的反射光
 *      ② 算法方法：对反光区域单独提高二值化阈值（分区大津法已经在做）
 *      ③ 环境方法：调整场地灯光角度，避免直射赛道外区域
 *
 *
 *  Q6: 换了一个场地，参数要全部重调吗？
 *  ──────────────────────────────────────────────────────────────
 *  A:  是的。不同场地的光照条件不同，曝光/增益需要重新适配。
 *      建议：每次比赛前花 10~15 分钟用上面的步骤快速调一遍。
 */


/* ============================================================================
 *  10. 高级：分区阈值 + 曝光联合调优
 * ============================================================================
 *
 *  本项目使用分区大津法（3 个区块独立阈值）：
 *
 *  ┌─────────┬────────────┬──────────────────────────────────────────┐
 *  │ 区块     │ 行范围      │ 作用                                     │
 *  ├─────────┼────────────┼──────────────────────────────────────────┤
 *  │ 远端 far │ row 0~19   │ 图像顶部（远处），受反光影响最大          │
 *  │ 中间 mid │ row 20~39  │ 图像中部，反光区通常在这里                │
 *  │ 近端 near│ row 40~59  │ 图像底部（近处），赛道入口                │
 *  └─────────┴────────────┴──────────────────────────────────────────┘
 *
 *  你的反光出现在"直角弯前方，row 38 附近" → 正好在 mid 区（row 20~39）。
 *
 *  联合调优策略：
 *  ─────────────────────────────────────────────────────────────────────
 *
 *  策略 1：降低曝光（推荐）
 *    → 远端、中间、近端三个区域同时变暗
 *    → 反光区域灰度值下降，大津法阈值也会相应调整
 *    → 效果最直接
 *
 *  策略 2：收紧中间区阈值范围
 *    → 修改 image.h 中的 THRESH_MIN / THRESH_MAX
 *    → 比如把 THRESH_MIN 从 80 提高到 100
 *    → 中间区的二值化阈值下限提高，白色判定更严格
 *    → 但可能影响暗区赛道识别
 *
 *  策略 3：分区阈值偏移
 *    → 在 image_binarize() 中给中间区的阈值加一个偏移量
 *    → 比如 tm += 15;  // 中间区阈值提高 15
 *    → 只影响中间区域，不影响远端和近端
 *
 *  推荐组合：曝光 80 + 增益 24 + 分区阈值保持不变
 *  ─────────────────────────────────────────────────────────────────────
 */


