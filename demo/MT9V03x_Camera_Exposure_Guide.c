/* ============================================================================
 *  1. 问题背景
 * ============================================================================
 *
 *  场景：赛道面积不大，直角弯前方没有贴赛道材料。
 *  现象：灯光照射到无赛道区域（桌面/地面），光线反射进摄像头，
 *        导致该区域灰度值很高，二值化后变成白色，误判为赛道。
 *
 *  根本原因：曝光时间太长 + 增益太高 → 反光区域收集了过多的光
 *
 *  解决思路（按优先级）：
 *    ① 降低曝光时间 —— 从源头减少进光量
 *    ② 降低图像增益 —— 减少信号放大倍数
 *    ③ 调整分区大津法阈值 —— 让二值化更严格（治标）
 *    ④ 物理遮光 —— 给摄像头加遮光罩（治本但不方便）
 */


/* ============================================================================
 *  2. MT9V03x 曝光原理
 * ============================================================================
 *
 *  MT9V03x 是一颗全局快门（Global Shutter）CMOS 传感器，像素值 = 光强 × 时间 × 增益。
 *
 *  一个像素的灰度值计算公式：
 *
 *      Pixel_Value = Light_Intensity × Exposure_Time × Gain × K
 *
 *  其中 K 是传感器内部常数。
 *
 *  控制画面亮度有三个旋钮：
 *
 *  ┌──────────────────┬──────────────┬──────────────────────────────────┐
 *  │ 参数              │ 范围         │ 效果                              │
 *  ├──────────────────┼──────────────┼──────────────────────────────────┤
 *  │ 曝光时间          │ 1 ~ 800+     │ 像素收集光的时间，越长越亮         │
 *  │ 图像增益          │ 16 ~ 64      │ 信号放大倍数，越大越亮（但噪声也大）│
 *  │ 自动曝光          │ 0 ~ 63       │ 0=关闭，非0=启用自动调节           │
 *  └──────────────────┴──────────────┴──────────────────────────────────┘
 *
 *  关键理解：
 *  ┌──────────────────────────────────────────────────────────────────────┐
 *  │  曝光时间是"主旋钮"，增益是"辅助旋钮"。                              │
 *  │                                                                      │
 *  │  曝光时间直接影响进光量，效果最明显；                                  │
 *  │  增益只是把信号放大，不增加真实信息，还会放大噪声。                      │
 *  │                                                                      │
 *  │  所以调参优先级：先调曝光，再调增益。                                   │
 *  └──────────────────────────────────────────────────────────────────────┘
 */


/* ============================================================================
 *  3. 曝光时间（Exposure Time）详解
 * ============================================================================
 *
 *  ┌─────────────────────────────────────────────────────────────────────┐
 *  │  设置函数：                                                          │
 *  │  mt9v03x_set_exposure_time_sccb(mt9v03x_1, value);                 │
 *  │                                                                     │
 *  │  参数：value = 曝光时间（无单位，越大越亮）                            │
 *  │  范围：1 ~ 800+（实际有效范围取决于帧率设置）                         │
 *  └─────────────────────────────────────────────────────────────────────┘
 *
 *  本质：曝光时间 = 传感器每帧采光的时长。
 *
 *  类比：像人眼的"快门速度"：
 *    - 快门速度快（曝光时间短）→ 进光少 → 画面暗
 *    - 快门速度慢（曝光时间长）→ 进光多 → 画面亮
 *
 *  对智能车的影响：
 *  ┌────────────┬───────────────────────────────────────────────────┐
 *  │ 曝光值      │ 效果                                              │
 *  ├────────────┼───────────────────────────────────────────────────┤
 *  │ 20 ~ 50    │ 很暗。暗区几乎全黑，亮区也变暗。适合强光/强反光场地  │
 *  │ 50 ~ 100   │ 偏暗。反光区域大幅减弱，正常赛道仍可辨识            │
 *  │ 100 ~ 200  │ 适中。大部分场景下平衡较好                          │
 *  │ 200 ~ 400  │ 偏亮。适合灯光较暗的场地                            │
 *  │ 400 ~ 800  │ 很亮。默认值 512 就在这个范围，容易出现反光问题      │
 *  └────────────┴───────────────────────────────────────────────────┘
 *
 *  ★ 曝光时间与帧率的关系：
 *  ─────────────────────────────────────────────────────────────────
 *  帧率 (FPS) 决定了每帧的最大可用曝光时间：
 *
 *    最大曝光时间 ≈ 1,000,000 / FPS（微秒）
 *
 *  例如：
 *    FPS = 100  → 最大曝光 ≈ 10,000 微秒（10ms）
 *    FPS = 50   → 最大曝光 ≈ 20,000 微秒（20ms）
 *    FPS = 25   → 最大曝光 ≈ 40,000 微秒（40ms）
 *
 *  如果曝光时间 > 最大可用时间，实际曝光会被截断为最大值。
 *  所以：帧率越高，曝光时间的可调范围越小。
 *
 *  本项目 FPS = 100，曝光时间可调范围足够用。
 *  ─────────────────────────────────────────────────────────────────
 */


/* ============================================================================
 *  4. 图像增益（Gain）详解
 * ============================================================================
 *
 *  ┌─────────────────────────────────────────────────────────────────────┐
 *  │  设置方式：在配置缓冲区中设置                                        │
 *  │  mt9v03x_set_confing_buffer_1[MT9V03X_DOUBLE_GAIN][1] = value;     │
 *  │                                                                     │
 *  │  参数：value = 增益值                                               │
 *  │  范围：16 ~ 64（默认 32）                                           │
 *  └─────────────────────────────────────────────────────────────────────┘
 *
 *  本质：增益 = 信号放大倍数。不改变实际进光量，只把已有的电信号放大。
 *
 *  类比：像音响的"音量"：
 *    - 音量小（增益低）→ 声音小，但底噪也小
 *    - 音量大（增益高）→ 声音大，但底噪也大（沙沙声明显）
 *
 *  对智能车的影响：
 *  ┌────────────┬───────────────────────────────────────────────────┐
 *  │ 增益值      │ 效果                                              │
 *  ├────────────┼───────────────────────────────────────────────────┤
 *  │ 16         │ 最低增益。画面最暗最干净，适合光线非常充足的场地     │
 *  │ 24         │ 低增益。轻微放大，噪声较小                          │
 *  │ 32         │ 默认值。平衡点                                      │
 *  │ 48         │ 高增益。画面明显变亮，噪声开始可见                   │
 *  │ 64         │ 最高增益。画面最亮，但噪声很大，边缘可能模糊         │
 *  └────────────┴───────────────────────────────────────────────────┘
 *
 *  ★ 噪声问题：
 *  ─────────────────────────────────────────────────────────────────
 *  增益越高，热噪声和读出噪声越大。在二值化图像上的表现为：
 *    - 黑色区域出现零星白点（椒盐噪声）
 *  这会导致八邻域爬线算法误判边界位置。
 *
 *  所以：增益尽量保持在 16~32 之间，除非场地光线真的很暗。
 *  ─────────────────────────────────────────────────────────────────
 */


/* ============================================================================
 *  5. 自动曝光 vs 手动曝光
 * ============================================================================
 *
 *  ┌──────────────────────────────────────────────────────────────────────┐
 *  │                                                                      │
 *  │   自动曝光（Auto Exposure）                                          │
 *  │   ────────────────────────                                           │
 *  │   摄像头自动调节曝光时间，使画面平均亮度保持在一个目标值。               │
 *  │                                                                      │
 *  │   设置：mt9v03x_set_confing_buffer_1[MT9V03X_DOUBLE_AUTO_EXP][1] = 1~63;│
 *  │   关闭：mt9v03x_set_confing_buffer_1[MT9V03X_DOUBLE_AUTO_EXP][1] = 0; │
 *  │                                                                      │
 *  │   优点：自动适应不同光照环境                                          │
 *  │   缺点：                                                             │
 *  │     - 调节有延迟，画面亮度会波动                                      │
 *  │     - 智能车赛道上黑白区域比例变化大，自动曝光会频繁调整                │
 *  │     - 导致二值化阈值不稳定，爬线算法容易出错                          │
 *  │                                                                      │
 *  │   结论：智能车比赛一般关闭自动曝光，使用手动曝光。                      │
 *  │                                                                      │
 *  └──────────────────────────────────────────────────────────────────────┘
 *
 *  ┌──────────────────────────────────────────────────────────────────────┐
 *  │                                                                      │
 *  │   手动曝光（Manual Exposure）  ← 本项目使用                           │
 *  │   ────────────────────────────                                       │
 *  │                                                                      │
 *  │   你固定曝光时间和增益，画面亮度完全由你控制。                          │
 *  │                                                                      │
 *  │   优点：                                                             │
 *  │     - 画面亮度稳定，二值化结果一致                                    │
 *  │     - 调一次参数，全场通用                                            │
 *  │                                                                      │
 *  │   缺点：                                                             │
 *  │     - 换场地需要重新调参                                              │
 *  │                                                                      │
 *  │   本项目配置：AUTO_EXP = 0（关闭），手动设置 EXP_TIME = 100          │
 *  │                                                                      │
 *  └──────────────────────────────────────────────────────────────────────┘
 */


